print("\n[5] Bi-LSTM (recomputed from models/helios_bilstm_edited.pt)")
import torch
import torch.nn as nn
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import mean_squared_error, mean_absolute_error, r2_score


class HeliosBiLSTM(nn.Module):
    def __init__(self, in_features, hidden_dim=64, num_layers=2):
        super().__init__()
        self.lstm = nn.LSTM(in_features, hidden_dim, num_layers, batch_first=True,
                            bidirectional=True, dropout=0.15)
        self.attention = nn.Sequential(nn.Linear(hidden_dim * 2, 32), nn.Tanh(), nn.Linear(32, 1))
        self.fc = nn.Sequential(nn.Linear(hidden_dim * 2, 32), nn.GELU(), nn.Linear(32, 1))

    def forward(self, x):
        out, _ = self.lstm(x)
        w = torch.softmax(self.attention(out), dim=1)
        return self.fc(torch.sum(out * w, dim=1))


SEQ = ["dst", "bz_gsm", "by_gsm", "b_mag", "v_flow", "np_dens", "temp", "pdyn",
       "ey_rectified", "newell_coupling", "akasofu_eps", "borovsky_coupling", "kp", "f107"]
