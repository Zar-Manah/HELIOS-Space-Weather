def check(label, claimed, measured, tol=0.011):
    global CHECKS
    CHECKS += 1
    ok = abs(float(claimed) - float(measured)) <= tol
    if not ok:
        FAILURES.append((label, claimed, measured))
    print(f"  {'PASS' if ok else 'FAIL'}  {label:52s} doc={claimed:<10} measured={measured}")


