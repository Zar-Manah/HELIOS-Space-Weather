test_df = omni[omni["year"] >= 2020].reset_index(drop=True)
scaler = StandardScaler().fit(train_df[SEQ])
Xs = scaler.transform(test_df[SEQ]).astype(np.float32)
ys = test_df["target_dst_lead_1h"].values.astype(np.float32)
net = HeliosBiLSTM(14)
net.load_state_dict(torch.load(os.path.join(MODELS, "helios_bilstm_edited.pt"), map_location="cpu"))
net.eval()
n_seq = len(Xs) - 24
preds = []
with torch.no_grad():
    for i in range(0, n_seq, 512):
        batch = np.stack([Xs[j:j + 24] for j in range(i, min(i + 512, n_seq))])
        preds.append(net(torch.tensor(batch)).numpy().ravel())
preds = np.concatenate(preds)
truth = ys[23:23 + len(preds)]
storm_true = truth <= -50
storm_pred = preds <= -50
tp = int(np.sum(storm_true & storm_pred))
tn = int(np.sum(~storm_true & ~storm_pred))
fp = int(np.sum(~storm_true & storm_pred))
fn = int(np.sum(storm_true & ~storm_pred))
tss = tp / (tp + fn) - fp / (fp + tn)
hss = 2 * (tp * tn - fp * fn) / ((tp + fn) * (fn + tn) + (tp + fp) * (fp + tn))
check("Bi-LSTM sequences (n)", 57974, len(preds), tol=0)
check("Bi-LSTM RMSE (nT)", 4.32, np.sqrt(mean_squared_error(truth, preds)), tol=0.02)
check("Bi-LSTM MAE (nT)", 2.54, mean_absolute_error(truth, preds), tol=0.02)
check("Bi-LSTM R2", 0.955, r2_score(truth, preds), tol=0.001)
check("Bi-LSTM TSS (Dst<=-50)", 0.958, tss, tol=0.002)
check("Bi-LSTM HSS (Dst<=-50)", 0.894, hss, tol=0.002)

